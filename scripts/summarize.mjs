// Read every recorded run under results/ and write results/summary.md.
// Refuses to mix runs of one profile made with different code, and flags
// any run where k6 could not start every shopper on schedule.
//
//   node scripts/summarize.mjs            (or RESULTS_DIR=my-results ...)
// Exits non-zero when any run is not a valid measurement.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.resolve(root, process.env.RESULTS_DIR || 'results');
const predictions = JSON.parse(fs.readFileSync(path.join(dir, 'predictions.json'), 'utf8'));

const runs = fs
  .readdirSync(dir)
  .filter((d) => fs.existsSync(path.join(dir, d, 'run.json')) && !d.startsWith('smoke'))
  .map((d) => {
    const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, d, f), 'utf8'));
    return { run: read('run.json'), k6: read('k6-summary.json').metrics, server: read('server-stats.json') };
  })
  .sort((a, b) => a.run.started.localeCompare(b.run.started));

const byProfile = {};
for (const r of runs) (byProfile[r.run.profile] ||= []).push(r);
for (const [profile, rs] of Object.entries(byProfile)) {
  const hashes = new Set(rs.map((r) => r.run.codeHash));
  if (hashes.size > 1) {
    console.error(`profile ${profile} mixes code versions: ${[...hashes].join(', ')}`);
    process.exit(1);
  }
}

const count = (m, k) => m[k]?.count ?? 0;
const ms = (m, k, stat) => (m[k]?.[stat] === undefined ? '' : `${Math.round(m[k][stat])}`);
const variant = (r) => {
  const e = r.run.serverEnv;
  if (e.ADMIT_LIMIT && e.ADMIT_LIMIT !== '0') return 'waiting room';
  if (e.DEADLINE === '1') return 'deadline';
  return e.MODE === 'naive' ? 'naive' : r.run.profile === 'peak' ? 'queue' : 'reserve';
};

let md = '# Recorded runs\n\nGenerated by `node scripts/summarize.mjs` from the files in each run folder.\n';
const problems = [];
for (const r of runs) {
  const dropped = count(r.k6, 'dropped_iterations');
  if (dropped) problems.push(`${r.run.label}: ${dropped} dropped iterations`);
  if (r.server.checkoutsInFlight !== 0) problems.push(`${r.run.label}: server had not drained`);
}
// Shoppers k6 v2.3.0 schedules for each profile (iterations plus dropped).
const SCHEDULED = { drop: 8249, low: 1124, peak: 2559, smoke: 29 };
for (const r of runs) {
  const expected = SCHEDULED[r.run.profile];
  const started = count(r.k6, 'iterations');
  if (expected && started !== expected) problems.push(`${r.run.label}: started ${started} of ${expected} scheduled shoppers`);
}
// Every run of a profile should start the same shoppers. k6 does not always
// count a shopper it never started as dropped, so compare across runs too.
for (const [profile, rs] of Object.entries(byProfile)) {
  const most = Math.max(...rs.map((r) => count(r.k6, 'iterations') + count(r.k6, 'dropped_iterations')));
  for (const r of rs) {
    const started = count(r.k6, 'iterations');
    if (started < most) problems.push(`${r.run.label}: started ${started} of ${most} shoppers scheduled in other ${profile} runs`);
  }
}

for (const profile of ['drop', 'low']) {
  const rs = byProfile[profile];
  if (!rs) continue;
  md += `\n## ${profile} (stock ${rs[0].server.stockInitial}, code ${rs[0].run.codeHash})\n\n`;
  md +=
    '| run | variant | shoppers | orders | oversold | final stock | purchases seen by k6 | checkout p95 ms | dropped | k6 exit | load before |\n';
  md += '|---|---|---|---|---|---|---|---|---|---|---|\n';
  for (const r of rs) {
    md += `| ${r.run.label} | ${variant(r)} | ${count(r.k6, 'iterations')} | ${r.server.orders} | ${r.server.oversold} | ${r.server.stockNow} | ${count(r.k6, 'purchases')} | ${ms(r.k6, 'http_req_duration{name:checkout}', 'p(95)')} | ${count(r.k6, 'dropped_iterations')} | ${r.run.k6Exit} | ${r.run.host.loadBefore} |\n`;
  }
  for (const v of ['naive', 'reserve']) {
    const p = predictions[`${profile}-${v}`];
    if (p) md += `\nPredicted ${v}: oversold mean ${p.oversold.mean} (5th to 95th percentile ${p.oversold.p5} to ${p.oversold.p95}) over ${predictions.trials} simulated runs.`;
  }
  md += '\n';
}

const peak = byProfile.peak;
if (peak) {
  md += `\n## peak (payment slots ${peak[0].server.config.payConcurrency}, code ${peak[0].run.codeHash})\n\n`;
  md +=
    '| run | variant | shoppers | purchases | orders to shoppers who had left | timeouts | skipped at deadline | gave up in waiting room | checkout request p95 ms | time to purchase median ms | time to purchase p95 ms | max checkouts in flight | waiting-room 503s | dropped | k6 exit |\n';
  md += '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n';
  for (const r of peak) {
    md += `| ${r.run.label} | ${variant(r)} | ${count(r.k6, 'iterations')} | ${count(r.k6, 'purchases')} | ${r.server.ordersToClientsThatHadLeft} | ${count(r.k6, 'client_timeouts')} | ${count(r.k6, 'skipped_past_deadline')} | ${count(r.k6, 'abandoned_in_waiting_room')} | ${ms(r.k6, 'checkout_ok_ms', 'p(95)')} | ${ms(r.k6, 'time_to_purchase_ms', 'med')} | ${ms(r.k6, 'time_to_purchase_ms', 'p(95)')} | ${r.server.maxCheckoutsInFlight} | ${r.server.waitingRoomRejected} | ${count(r.k6, 'dropped_iterations')} | ${r.run.k6Exit} |\n`;
  }
  md += '\nPredicted (mean over simulated runs, server CPU time ignored):\n\n';
  md += '| variant | purchases | orders to shoppers who had left | time to purchase median s | time to purchase p95 s |\n|---|---|---|---|---|\n';
  for (const [k, name] of [
    ['peak-queue', 'queue'],
    ['peak-deadline', 'deadline'],
    ['peak-waitingroom', 'waiting room'],
  ]) {
    const p = predictions[k];
    md += `| ${name} | ${p.purchases.mean} | ${p.ghosts.mean} | ${p.ttpMedian.mean} | ${p.ttpP95.mean} |\n`;
  }
}

md += problems.length ? `\n## Problems\n\n${problems.map((p) => `- ${p}`).join('\n')}\n` : '\nNo dropped iterations, every server drained before counting.\n';
fs.writeFileSync(path.join(dir, 'summary.md'), md);
console.log(md);
if (problems.length) process.exit(1);
